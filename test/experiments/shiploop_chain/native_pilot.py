def utc_now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(read_regular(path, str(path)))


def fail(message: str) -> None:
    raise PilotError(message)


def absolute_path(value: str, label: str, *, exists: bool = False) -> Path:
    path = Path(value).expanduser()
    if not path.is_absolute():
        fail(f"{label} must be an absolute path")
    try:
        resolved = path.resolve(strict=exists)
    except OSError as exc:
        fail(f"cannot resolve {label}: {exc}")
    if exists and not resolved.exists():
        fail(f"{label} does not exist")
    return resolved


def under(parent: Path, child: Path) -> bool:
    try:
        child.resolve().relative_to(parent.resolve())
        return True
    except ValueError:
        return False


def read_regular(path: Path, label: str) -> bytes:
    try:
        before = path.lstat()
    except OSError as exc:
        fail(f"cannot inspect {label}: {exc}")
    if not path.is_file() or path.is_symlink():
        fail(f"{label} must be a regular non-symlink file")
    try:
        data = path.read_bytes()
        after = path.stat()
    except OSError as exc:
        fail(f"cannot read {label}: {exc}")
    if (before.st_dev, before.st_ino, before.st_size) != (after.st_dev, after.st_ino, after.st_size):
        fail(f"{label} changed while it was read")
    return data


def json_object(path: Path, label: str) -> dict[str, Any]:
    try:
        value = json.loads(read_regular(path, label).decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        fail(f"{label} is not valid JSON: {exc}")
    if not isinstance(value, dict):
        fail(f"{label} must contain one JSON object")
    return value


def json_bytes(value: Any) -> bytes:
    return (json.dumps(value, sort_keys=True, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def write_new(path: Path, data: bytes, label: str) -> None:
    if os.path.lexists(path):
        fail(f"refusing to overwrite existing {label}: {path}")
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    try:
        with path.open("xb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
    except OSError as exc:
        fail(f"cannot write {label}: {exc}")


def write_new_json(path: Path, value: Any, label: str) -> None:
    write_new(path, json_bytes(value), label)


def write_same_or_new_json(path: Path, value: Any, label: str) -> None:
    data = json_bytes(value)
    if os.path.lexists(path):
        if read_regular(path, label) != data:
            fail(f"existing {label} differs from this invocation: {path}")
        return
    write_new(path, data, label)


def pilot_root(value: str) -> Path:
    root = absolute_path(value, "--pilot-dir", exists=True)
    if not root.is_dir() or root.is_symlink():
        fail("--pilot-dir must be an existing real directory")
    return root


def read_context(root: Path) -> dict[str, Any]:
    context = json_object(root / "context.json", "pilot context")
    required = {"schema", "pilot_dir", "selected", "fixture", "run", "graph", "oracle"}
    if not required <= set(context):
        fail("pilot context is incomplete")
    if context["pilot_dir"] != str(root):
        fail("pilot context belongs to a different directory")
    return context


def next_command_number(root: Path) -> int:
    records = list((root / "commands").glob("*.json"))
    return len(records) + 1


def append_event(root: Path, event: dict[str, Any]) -> None:
    path = root / "events.jsonl"
    raw = (json.dumps(event, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")
    descriptor = os.open(path, os.O_APPEND | os.O_CREAT | os.O_WRONLY, 0o600)
    try:
        os.write(descriptor, raw)
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def run_command(root: Path, label: str, argv: list[str], *, allowed: Iterable[int] = (0,), timeout: int = 60,
                input_path: Path | None = None) -> subprocess.CompletedProcess[str]:
    sequence = next_command_number(root)
    try:
        result = subprocess.run(argv, text=True, capture_output=True, timeout=timeout, check=False,
                                env={**os.environ, "GIT_TERMINAL_PROMPT": "0"}, shell=False)
    except (OSError, subprocess.TimeoutExpired) as exc:
        record = {"schema": "shiploop-native-pilot-command/v1", "sequence": sequence, "label": label,
                  "argv": argv, "recorded_at": utc_now(), "error": str(exc),
                  "input_path": None if input_path is None else str(input_path)}
        record_path = root / "commands" / f"{sequence:04d}-{label}.json"
        write_new_json(record_path, record, "command record")
        append_event(root, {"kind": "command", "record": str(record_path), "error": str(exc), "at": utc_now()})
        fail(f"{label} could not run: {exc}")
    record = {
        "schema": "shiploop-native-pilot-command/v1",
        "sequence": sequence,
        "label": label,
        "argv": argv,
        "recorded_at": utc_now(),
        "returncode": result.returncode,
        "stdout": result.stdout,
        "stderr": result.stderr,
        "input_path": None if input_path is None else str(input_path),
    }
    record_path = root / "commands" / f"{sequence:04d}-{label}.json"
    write_new_json(record_path, record, "command record")
    append_event(root, {"kind": "command", "record": str(record_path), "returncode": result.returncode,
                        "stdout_sha256": sha256_bytes(result.stdout.encode()),
                        "stderr_sha256": sha256_bytes(result.stderr.encode()), "at": utc_now()})
    if result.returncode not in set(allowed):
        detail = (result.stderr or result.stdout).strip()
        fail(f"{label} failed with exit {result.returncode}: {detail[:1200]}")
    return result


def git(root: Path, repo: Path, label: str, *args: str, allowed: Iterable[int] = (0,)) -> subprocess.CompletedProcess[str]:
    return run_command(root, "git-" + label, ["git", "-C", str(repo), *args], allowed=allowed)


def git_text(root: Path, repo: Path, label: str, *args: str) -> str:
    return git(root, repo, label, *args).stdout.strip()


def assert_clean(root: Path, repo: Path, label: str) -> None:
    status = git_text(root, repo, label + "-status", "status", "--porcelain=v1", "--untracked-files=all")
    if status:
        fail(f"{label} must be clean; found: {status}")


def bridge(context: dict[str, Any], operation: str, *, payload: dict[str, Any] | None = None,
           extra: list[str] | None = None) -> dict[str, Any]:
    root = Path(context["pilot_dir"])
    selected = context["selected"]
    argv = [selected["python"], "-B", selected["shiploop_cli"], "chain", operation,
            "--run-dir", context["run"]["run_dir"], "--action", context["run"]["action"]]
    if extra:
        argv.extend(extra)
    input_path: Path | None = None
    if payload is not None:
        input_path = root / "inputs" / f"{uuid.uuid4().hex}-{operation}.json"
        write_new_json(input_path, payload, "bridge input")
        argv.extend(["--input", str(input_path)])
    result = run_command(root, "chain-" + operation, argv, input_path=input_path)
    try:
        value = json.loads(result.stdout)
    except json.JSONDecodeError as exc:
        fail(f"public chain {operation} returned non-JSON output: {exc}")
    if not isinstance(value, dict):
        fail(f"public chain {operation} returned a non-object")
    return value


