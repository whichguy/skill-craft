"""Static prompt text that lives in reference files and is inserted into packets word for word.

Owner, 2026-10-17: guidance that does not change between runs is read from `references/` and printed as written, never
regenerated by a model; only values from state are rendered around it. A missing file or section is an error, never a
fallback.
"""
from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from typing import Optional

REFERENCES = Path(__file__).resolve().parent.parent / "references"


class StaticTextError(RuntimeError):
    """A static text file or one of its sections is missing."""


@lru_cache(maxsize=None)
def _read(name: str) -> str:
    path = REFERENCES / name
    try:
        return path.read_text(encoding="utf-8")
    except OSError as exc:
        raise StaticTextError(f"static text {path} is missing: {exc}") from exc


def static_text(name: str, section: Optional[str] = None) -> str:
    """The text of ``references/<name>``, or of its ``## <section>`` (heading line included) up to the next ``## ``.

    ``name`` is a file name under ``references/``; ``section`` is a level-2 heading's text. Raises
    ``StaticTextError`` naming the file and the heading when either is missing.
    """
    if not isinstance(name, str) or not name or Path(name).name != name:
        raise StaticTextError(f"static text name must be a file name under {REFERENCES}, got {name!r}")
    text = _read(name)
    if section is None:
        return text
    lines = text.splitlines(keepends=True)
    heading = "## " + section
    starts = [index for index, line in enumerate(lines) if line.rstrip("\n") == heading]
    if len(starts) != 1:
        raise StaticTextError(f"static text {REFERENCES / name} needs exactly one '{heading}' heading, "
                              f"found {len(starts)}")
    start = starts[0]
    end = next((index for index in range(start + 1, len(lines)) if lines[index].startswith("## ")), len(lines))
    return "".join(lines[start:end]).rstrip("\n") + "\n"


__all__ = ["REFERENCES", "StaticTextError", "static_text"]
