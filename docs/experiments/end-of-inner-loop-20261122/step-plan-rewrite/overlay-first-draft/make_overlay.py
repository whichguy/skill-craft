#!/usr/bin/env python3
"""Write overlay.json from wording/*.txt, the one place each proposed text lives.

    python3 make_overlay.py        # writes overlay.json beside this file and checks that it applies to this checkout's scripts

- ``wording/step-plan-duty-10.txt`` replaces step-plan duty 10 from "Keep every R-<n> and AD-<n>;" to the end of the duty. The
  words are the file's; the line breaks are the source's (wrapped at 120 columns, four spaces of indent), so only the lines the
  words change differ. Change the file, run this again, and nothing else needs an edit.
- ``wording/document-duty-3.txt`` and ``wording/step-spec-refusal.txt`` replace the same words in ``document``'s duty 3 and in
  ``step_spec_refusal``. No step-plan packet prints either; they are here so that the treated build is the design's.
"""
from __future__ import annotations

import ast
import json
import sys
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
sys.path.insert(0, str(ROOT / "test" / "shiploop_e2e"))
import overlay  # noqa: E402

PROMPTS = (overlay.SCRIPTS / "shiploop_prompts.py").read_text()
WIDTH, INDENT = 120, "    "
SPLIT = "Keep every R-<n> and AD-<n>;"
DUTY = ("10. **Knowledge.**", '""" + _STEP_PLAN_NO_GRAPH')


def wording(name: str) -> str:
    return " ".join((HERE / "wording" / name).read_text().split())


def wrap(text: str, width: int, indent: str) -> str:
    return "\n".join(textwrap.wrap(text, width, initial_indent="", subsequent_indent=indent, break_long_words=False,
                                   break_on_hyphens=False)) + "\n"


def step_plan_edit() -> dict:
    start = PROMPTS.index(DUTY[0] + " A structural choice")
    duty = PROMPTS[start:PROMPTS.index(DUTY[1], start)]
    flat = " ".join(duty.split())
    if wrap(flat, WIDTH, INDENT) != duty or flat.count(SPLIT) != 1:
        raise SystemExit("step-plan duty 10 is not wrapped as this script expects: look at the source before changing it")
    new = wrap(flat[:flat.index(SPLIT)] + wording("step-plan-duty-10.txt"), WIDTH, INDENT)
    old_lines, new_lines = duty.splitlines(keepends=True), new.splitlines(keepends=True)
    same = next((n for n, (a, b) in enumerate(zip(old_lines, new_lines)) if a != b), min(len(old_lines), len(new_lines)))
    return {"module": "shiploop_prompts.py", "constant": "DUTIES", "key": "step-plan",
            "old": "".join(old_lines[same:]), "new": "".join(new_lines[same:])}


def document_edit() -> dict:
    old = "     Add lines only; a requirement whose intent moved is no edit: report send-back naming the R-<n>.\n"
    flat = old.strip().replace("report send-back naming the R-<n>.", wording("document-duty-3.txt"))
    new = "\n".join(textwrap.wrap(flat, WIDTH, initial_indent="     ", subsequent_indent="     ", break_long_words=False,
                                  break_on_hyphens=False)) + "\n"
    return {"module": "shiploop_prompts.py", "constant": "DUTIES", "key": "document", "old": old, "new": new}


def refusal_edit() -> dict:
    return {"module": "shiploop_knowledge_home.py", "function": "step_spec_refusal",
            "old": "to change a requirement, report send-back naming it.", "new": wording("step-spec-refusal.txt")}


def main() -> None:
    data = {"about": "step-plan rewrites a requirement the send-back it answers names (step-plan-rewrite-design.md, The change, items 1 "
                     "and 2). Generated by make_overlay.py from wording/*.txt: edit those, not this.",
            "edits": [step_plan_edit(), document_edit(), refusal_edit()]}
    out = HERE / "overlay.json"
    out.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")
    problems = overlay.check(out)
    print("\n".join(problems) or f"{out}: applies")
    for edit in data["edits"]:
        ast.parse('x = """' + edit["new"] + '"""') if edit.get("constant") else None
    raise SystemExit(1 if problems else 0)


if __name__ == "__main__":
    main()
